#!/usr/bin/env python3
"""Distribute the .agents/ SSOT into each AI tool's native discovery locations.

Companion to doc/dotagents/init_dotagents_folder.py, which only creates and
validates the .agents/ folder. Pure standard library; Windows / macOS / Linux,
Python 3.8+; self-contained (no imports from the init script).

Usage:
    python scripts/distribute.py distribute [--root PATH] [--scope project|user]
                                            [--targets claude,codex,opencode,copilot]
                                            [--config PATH]
    python scripts/distribute.py undistribute [--root PATH] [--scope project|user]
                                              [--targets claude,codex,opencode,copilot]
                                              [--config PATH]

Strategy matrix (verified 2026-08-30 against official docs — see
tickets/requirement/multi-tool-distribution.md §3):

- Claude Code:  .claude/agents/<name> and .claude/skills/<name> links (recursive
                scan, identity from frontmatter name; symlinked skill dirs are
                officially supported)
- Copilot (VS Code): .github/agents/<name>.md and .github/skills/<name> (project);
                ~/.copilot/agents/<name>.md and the shared ~/.agents/skills/<name> (user)
- OpenCode:     generated <agents_dir>/<name>.md (filename = agent name, frontmatter
                filtered to description + mode: subagent); skills discovered in .agents/ natively
- Codex:        generated agents/<name>.toml (name, description, developer_instructions);
                skills discovered in .agents/ natively

Windows without symlink privilege: directory links fall back to junctions, file
links to same-volume hardlinks. Exclusions and defaults live in
.agents/distribute.json in the project root (data-side config, following the
protocol's .agents/ convergence, decoupled from script location). The manifest
(.agents/.backups/distribute-manifest.json) records exactly what was created so
undistribute removes exactly that.
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

TOOLS = ["claude", "codex", "opencode", "copilot"]
SHARED_SKILL_TARGETS = {"codex", "opencode", "copilot"}  # user scope: one ~/.agents/skills link serves all
MARKER = "auto-generated by scripts/distribute.py"

DEFAULT_CONFIG = {
    "default_scope": "project",
    "default_targets": TOOLS,
    "exclude": {"agents": [], "skills": [], "per_target": {}},
    "opencode": {"agents_dir": "agents"},  # current docs say agents/; older releases used agent/
}


def atomic_write(path: Path, content: str) -> None:
    """Safe-by-default write: temp file + rename (atomic on POSIX and Windows)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        os.replace(tmp, str(path))
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def json_text(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True) + "\n"


def parse_frontmatter(text: str):
    """Parse simple '---' fenced key:value frontmatter. Returns (dict, body).

    Not full YAML by design; matching surrounding quotes on a value are
    stripped so `name: "x"` == `name: x`. Returns (None, text) without a
    complete frontmatter block.
    """
    if not text.startswith("---"):
        return None, text
    lines = text.splitlines()
    meta = {}
    for i, line in enumerate(lines[1:], start=1):
        if line.strip() == "---":
            return meta, "\n".join(lines[i + 1:])
        key, sep, value = line.partition(":")
        if sep:
            value = value.strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
                value = value[1:-1]
            meta[key.strip()] = value
    return None, text


def list_ssot(root: Path, kind: str):
    """Names of SSOT entries: agents/<name>/agent.md or skills/<name>/SKILL.md."""
    directory = root / ".agents" / kind
    entry_file = "agent.md" if kind == "agents" else "SKILL.md"
    if not directory.is_dir():
        return []
    return sorted(c.name for c in directory.iterdir()
                  if c.is_dir() and (c / entry_file).is_file())


def default_config_path(root: Path) -> Path:
    return root / ".agents" / "distribute.json"


def load_config(config_path: Path) -> dict:
    config = json.loads(json.dumps(DEFAULT_CONFIG))  # deep copy
    if config_path.is_file():
        user = json.loads(config_path.read_text(encoding="utf-8"))
        for key in ("default_scope", "default_targets"):
            if key in user:
                config[key] = user[key]
        for key, value in user.get("exclude", {}).items():
            if key == "per_target":
                config["exclude"]["per_target"].update(value)
            else:
                config["exclude"][key] = value
        config["opencode"].update(user.get("opencode", {}))
    return config


def is_excluded(config: dict, kind: str, name: str, target: str) -> bool:
    exclude = config.get("exclude", {})
    if name in exclude.get(kind, []):
        return True
    per_target = exclude.get("per_target", {}).get(target, {})
    return name in per_target.get(kind, [])


def make_link(source: Path, link: Path, is_dir: bool) -> str:
    """Create link -> source; returns how: 'symlink', 'junction', or 'hardlink'.

    Windows falls back because directory symlinks need Developer Mode/admin:
    junctions for directories, hardlinks for files (same volume only).
    """
    try:
        os.symlink(str(source), str(link), target_is_directory=is_dir)
        return "symlink"
    except OSError:
        if os.name == "nt":
            kind = "/J" if is_dir else "/H"
            result = subprocess.run(
                ["cmd", "/c", "mklink", kind, str(link), str(source)],
                capture_output=True, text=True)
            if result.returncode == 0:
                return "junction" if is_dir else "hardlink"
            detail = (result.stderr or result.stdout).strip()
            hint = ""
            if not is_dir:
                hint = ("; a file hardlink needs the same volume, and a real symlink "
                        "needs Developer Mode or an elevated shell")
            raise OSError(f"symlink failed and 'mklink {kind}' failed: {detail}{hint}")
        raise


def link_points_to(link: Path, source: Path) -> bool:
    """True when link resolves to source (symlink/junction) or IS source (hardlink)."""
    try:
        if os.path.realpath(str(link)) == os.path.realpath(str(source)):
            return True
        if os.name == "nt":
            ls, ss = os.stat(str(link)), os.stat(str(source))
            return (ls.st_dev, ls.st_ino) == (ss.st_dev, ss.st_ino)
    except OSError:
        pass
    return False


def remove_link(path: Path) -> bool:
    for remover in (os.unlink, os.rmdir):
        try:
            remover(str(path))
            return True
        except OSError:
            continue
    return False


# --- generated-file renderers ---------------------------------------------------

def yaml_quote(value: str) -> str:
    return json.dumps(value)  # a JSON string is a valid YAML double-quoted scalar


def toml_quote(value: str) -> str:
    out = (value.replace("\\", "\\\\").replace('"', '\\"')
                .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t"))
    return f'"{out}"'


def toml_multiline(body: str) -> str:
    body = body.replace("\r\n", "\n")
    if not body.endswith("\n"):
        body += "\n"
    if "'''" not in body:
        return "'''\n" + body + "'''"
    return json.dumps(body)  # fallback: escaped single-line basic string


def marker_line(source_rel: str) -> str:
    return f"# {MARKER} — source: {source_rel}"


def read_agent(root: Path, name: str):
    text = (root / ".agents" / "agents" / name / "agent.md").read_text(encoding="utf-8")
    meta, body = parse_frontmatter(text)
    if meta is None:
        meta, body = {}, text
    return meta, body


def render_opencode_agent(name: str, meta: dict, body: str) -> str:
    fm = [
        "---",
        marker_line(f".agents/agents/{name}/agent.md"),
        f"description: {yaml_quote(meta.get('description', ''))}",
        "mode: subagent",
        "---",
        "",
        body,
    ]
    text = "\n".join(fm)
    return text if text.endswith("\n") else text + "\n"


def render_codex_agent(name: str, meta: dict, body: str) -> str:
    return "\n".join([
        marker_line(f".agents/agents/{name}/agent.md"),
        f"name = {toml_quote(name)}",
        f"description = {toml_quote(meta.get('description', ''))}",
        "",
        f"developer_instructions = {toml_multiline(body)}",
        "",
    ])


# --- plan ------------------------------------------------------------------------

def build_plan(root: Path, scope: str, targets, config: dict):
    """Distribution plan: list of action dicts.

    link     -> dest symlink/junction/hardlink to source
    generate -> dest file rendered from the SSOT entry
    native   -> the tool discovers the SSOT location itself, nothing to do
    """
    home = Path.home()
    opencode_dir = config.get("opencode", {}).get("agents_dir", "agents")
    plan = []

    for target in targets:
        for name in list_ssot(root, "agents"):
            if is_excluded(config, "agents", name, target):
                continue
            src_dir = (root / ".agents" / "agents" / name).resolve()
            src_file = src_dir / "agent.md"
            if target == "claude":
                base = root if scope == "project" else home
                plan.append(dict(action="link", kind="agents", target=target, name=name,
                                 dest=base / ".claude" / "agents" / name,
                                 source=src_dir, is_dir=True))
            elif target == "copilot":
                base = root / ".github" if scope == "project" else home / ".copilot"
                plan.append(dict(action="link", kind="agents", target=target, name=name,
                                 dest=base / "agents" / f"{name}.md",
                                 source=src_file, is_dir=False))
            elif target == "opencode":
                base = root / ".opencode" if scope == "project" else home / ".config" / "opencode"
                plan.append(dict(action="generate", kind="agents", target=target, name=name,
                                 dest=base / opencode_dir / f"{name}.md",
                                 renderer="opencode"))
            elif target == "codex":
                base = root / ".codex" if scope == "project" else home / ".codex"
                plan.append(dict(action="generate", kind="agents", target=target, name=name,
                                 dest=base / "agents" / f"{name}.toml",
                                 renderer="codex"))

        for name in list_ssot(root, "skills"):
            if is_excluded(config, "skills", name, target):
                continue
            src_dir = (root / ".agents" / "skills" / name).resolve()
            if target == "claude":
                base = root if scope == "project" else home
                plan.append(dict(action="link", kind="skills", target=target, name=name,
                                 dest=base / ".claude" / "skills" / name,
                                 source=src_dir, is_dir=True))
            elif target == "copilot" and scope == "project":
                plan.append(dict(action="link", kind="skills", target=target, name=name,
                                 dest=root / ".github" / "skills" / name,
                                 source=src_dir, is_dir=True))
            elif target in SHARED_SKILL_TARGETS and scope == "user":
                # One ~/.agents/skills/<name> link serves Codex, OpenCode, and Copilot.
                plan.append(dict(action="link", kind="skills", target=target, name=name,
                                 dest=home / ".agents" / "skills" / name,
                                 source=src_dir, is_dir=True))
            elif scope == "project":
                plan.append(dict(action="native", kind="skills", target=target, name=name))
    return plan


# --- manifest ---------------------------------------------------------------------

def manifest_path(root: Path) -> Path:
    return root / ".agents" / ".backups" / "distribute-manifest.json"


def load_manifest(root: Path) -> dict:
    path = manifest_path(root)
    if path.is_file():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            if isinstance(data, dict) and isinstance(data.get("entries"), dict):
                return data
        except json.JSONDecodeError:
            print(f"warn: manifest unreadable, starting fresh: {path}", file=sys.stderr)
    return {"version": 1, "entries": {}}


def save_manifest(root: Path, manifest: dict) -> None:
    atomic_write(manifest_path(root), json_text(manifest))


# --- commands ----------------------------------------------------------------------

def cmd_distribute(root: Path, scope, targets, config_path: Path) -> int:
    config = load_config(config_path)
    scope = scope or config.get("default_scope", "project")
    if scope not in ("project", "user"):
        print(f"error: --scope must be 'project' or 'user', got {scope!r}", file=sys.stderr)
        return 2
    if not targets:
        targets = list(config.get("default_targets", TOOLS))
    unknown = [t for t in targets if t not in TOOLS]
    if unknown:
        print(f"error: unknown targets {unknown}; valid: {TOOLS}", file=sys.stderr)
        return 2

    plan = build_plan(root, scope, targets, config)
    manifest = load_manifest(root)
    entries = manifest["entries"]
    problems = 0
    counts = {"new": 0, "updated": 0, "skip": 0, "native": 0}

    for item in plan:
        if item["action"] == "native":
            counts["native"] += 1
            print(f"[native] {item['target']} discovers skills/{item['name']} in .agents/ itself")
            continue
        dest, target, name = item["dest"], item["target"], item["name"]

        if item["action"] == "link":
            if os.path.lexists(dest):
                if link_points_to(dest, item["source"]):
                    counts["skip"] += 1
                    print(f"[skip  ] {dest} already links to source")
                else:
                    problems += 1
                    print(f"[conflict] {dest} exists but does not point to "
                          f"{item['source']} — resolve manually", file=sys.stderr)
            else:
                dest.parent.mkdir(parents=True, exist_ok=True)
                try:
                    how = make_link(item["source"], dest, item["is_dir"])
                except OSError as exc:
                    problems += 1
                    print(f"[error ] cannot create link {dest}: {exc}", file=sys.stderr)
                    continue
                counts["new"] += 1
                print(f"[link  ] {dest} -> {item['source']} ({how})")

        elif item["action"] == "generate":
            meta, body = read_agent(root, name)
            if item["renderer"] == "opencode":
                content = render_opencode_agent(name, meta, body)
            else:
                content = render_codex_agent(name, meta, body)
            if dest.exists():
                text = dest.read_text(encoding="utf-8")
                if MARKER not in text:
                    problems += 1
                    print(f"[conflict] {dest} exists without the generated marker — "
                          f"not overwriting a foreign file", file=sys.stderr)
                    continue
                if text == content:
                    counts["skip"] += 1
                    print(f"[skip  ] {dest} up to date")
                else:
                    atomic_write(dest, content)
                    counts["updated"] += 1
                    print(f"[update] {dest} regenerated from SSOT")
            else:
                atomic_write(dest, content)
                counts["new"] += 1
                print(f"[gen   ] {dest} generated from SSOT")

        entry = entries.setdefault(str(dest), {
            "source": str(item.get("source", "")),
            "kind_of": item["action"], "scope": scope, "targets": [],
        })
        entry["targets"] = sorted(set(entry["targets"]) | {target})

    save_manifest(root, manifest)
    print(f"\n{scope}-scope distribute to {', '.join(targets)}: "
          f"{counts['new']} new, {counts['updated']} updated, {counts['skip']} unchanged, "
          f"{counts['native']} native, {problems} conflict(s).")
    if problems:
        print("FAIL: resolve the conflicts above and re-run", file=sys.stderr)
        return 1
    return 0


def cmd_undistribute(root: Path, scope, targets, config_path: Path) -> int:
    config = load_config(config_path)  # same config so defaults stay symmetric
    if scope is None and targets is None:
        scope_filter = None
        target_filter = None
    else:
        scope_filter = scope or config.get("default_scope", "project")
        target_filter = set(targets) if targets else None
        if scope_filter not in (None, "project", "user"):
            print(f"error: --scope must be 'project' or 'user', got {scope_filter!r}",
                  file=sys.stderr)
            return 2

    manifest = load_manifest(root)
    entries = manifest["entries"]
    removed = kept_partial = foreign = 0
    problems = 0

    for path_str in sorted(entries):
        entry = entries[path_str]
        if scope_filter is not None and entry.get("scope") != scope_filter:
            continue
        owned = set(entry.get("targets", []))
        if target_filter is not None:
            dropping = owned & target_filter
            if not dropping:
                continue
            remaining = owned - target_filter
            if remaining:
                # e.g. the shared ~/.agents/skills link still serves other tools
                entry["targets"] = sorted(remaining)
                kept_partial += 1
                print(f"[keep  ] {path_str} still serves {sorted(remaining)}")
                continue

        path = Path(path_str)
        drop_entry = False
        if entry.get("kind_of") == "link":
            if not os.path.lexists(path):
                print(f"[gone  ] {path_str} already absent")
                drop_entry = True
            elif link_points_to(path, Path(entry["source"])):
                if remove_link(path):
                    removed += 1
                    print(f"[rm    ] {path_str}")
                else:
                    problems += 1
                    print(f"[error ] could not remove link {path_str}", file=sys.stderr)
                drop_entry = True
            else:
                foreign += 1
                print(f"[foreign] {path_str} no longer points to {entry['source']} — "
                      f"leaving it alone", file=sys.stderr)
        elif entry.get("kind_of") == "generate":
            if not path.exists():
                print(f"[gone  ] {path_str} already absent")
                drop_entry = True
            elif MARKER in path.read_text(encoding="utf-8")[:400]:
                path.unlink()
                removed += 1
                print(f"[rm    ] {path_str}")
                drop_entry = True
            else:
                foreign += 1
                print(f"[foreign] {path_str} lost its generated marker — leaving it alone",
                      file=sys.stderr)
        if drop_entry:
            del entries[path_str]

    save_manifest(root, manifest)
    print(f"\nundistribute: {removed} removed, {kept_partial} kept for remaining targets, "
          f"{foreign} foreign, {problems} error(s).")
    return 1 if (problems or foreign) else 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    for name, help_text in (
        ("distribute", "install SSOT agents/skills into each tool's discovery location"),
        ("undistribute", "remove exactly what distribute created (per the manifest)"),
    ):
        p = sub.add_parser(name, help=help_text)
        p.add_argument("--root", type=Path, default=Path.cwd(), help="project root (default: cwd)")
        p.add_argument("--scope", choices=["project", "user"],
                       help="project = repo-local tool dirs, user = home-level (default: config)")
        p.add_argument("--targets", metavar="A,B,C",
                       help=f"comma-separated subset of {','.join(TOOLS)} (default: config)")
        p.add_argument("--config", type=Path, default=None,
                       help="distribute config (default: .agents/distribute.json under --root)")

    args = parser.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):  # Windows consoles default to a legacy codepage
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        sys.stderr.reconfigure(encoding="utf-8", errors="replace")

    targets = None
    if args.targets:
        targets = [t.strip() for t in args.targets.split(",") if t.strip()]
    config_path = args.config or default_config_path(args.root)
    if args.command == "distribute":
        return cmd_distribute(args.root, args.scope, targets, config_path)
    return cmd_undistribute(args.root, args.scope, targets, config_path)


if __name__ == "__main__":
    sys.exit(main())
