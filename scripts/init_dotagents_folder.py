#!/usr/bin/env python3
"""Initialize, validate, and distribute a .agents/ directory per the .agents Protocol.

Protocol reference: https://dotagentsprotocol.com/ (see doc/dotagents-protocol.md)

Pure standard library; runs on Windows / macOS / Linux with Python 3.8+.

Usage:
    python scripts/init_dotagents_folder.py init [--root PATH] [--examples] [--force]
    python scripts/init_dotagents_folder.py validate [--root PATH]
    python scripts/init_dotagents_folder.py distribute [--root PATH] [--scope project|user]
                                                        [--targets claude,codex,opencode,copilot]
                                                        [--config PATH]
    python scripts/init_dotagents_folder.py undistribute [--root PATH] [--scope project|user]
                                                          [--targets claude,codex,opencode,copilot]
                                                          [--config PATH]

Distribution maps the SSOT (.agents/agents/<name>/agent.md and
.agents/skills/<name>/SKILL.md) onto each tool's native discovery location:

- Claude Code:    .claude/agents/<name> and .claude/skills/<name> symlinks (recursive scan,
                  identity from frontmatter name; skill directories may be symlinks)
- Copilot (VS Code): .github/agents/<name>.md and .github/skills/<name> (project);
                  ~/.copilot/agents/<name>.md and the shared ~/.agents/skills/<name> (user)
- OpenCode:       generated <agents_dir>/<name>.md (filename = agent name; frontmatter
                  filtered to description + mode); skills discovered in .agents/ natively
- Codex:          generated agents/<name>.toml (name, description, developer_instructions);
                  skills discovered in .agents/ natively

Exclusions and defaults live in distribute.json next to this script.
"""

